"""
Agent 4: Visual Scene & Render Engine Compiler
Prepares Remotion component props for MasterAutonomousReel, coordinates camera zooms,
environment props, character rosters, and executes headless MP4 rendering.
"""

import json
import os
import shutil
import subprocess
import sys
import time
from pathlib import Path
from typing import Dict, Any

PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
REMOTION_DIR = PROJECT_ROOT / "my-edu-reels"


class SceneDirectorAgent:
    """Agent 4: Compiles scene props and renders 1080x1920 MP4 via Remotion."""

    def __init__(self, project_root: Path = PROJECT_ROOT):
        self.project_root = project_root
        self.remotion_dir = self.project_root / "my-edu-reels"
        self.public_dir = self.project_root / "public"
        self.remotion_public = self.remotion_dir / "public"
        self.out_dir = self.project_root / "out"
        self.out_dir.mkdir(parents=True, exist_ok=True)
        self.remotion_public.mkdir(parents=True, exist_ok=True)

    def compile_and_render(
        self,
        script_data: Dict[str, Any],
        audio_result: Dict[str, Any],
        output_name: str = "daily_ai_reel.mp4"
    ) -> str:
        print("🎬 [Agent 4: Scene Director] Assembling visual props and rendering MP4...")

        # Sync voice, subtitles, timeline, and envelope into remotion public directory
        for fname in ["voice.mp3", "voiceover.mp3", "master.mp3", "subs.json", "subs.vtt", "video-meta.json", "timeline.json", "audio_envelope.json"]:
            src_file = self.public_dir / fname
            dst_file = self.remotion_public / fname
            if src_file.exists() and os.path.realpath(str(src_file)) != os.path.realpath(str(dst_file)):
                shutil.copy2(src_file, dst_file)

        # Load timeline data (or fallback to subs) generated by Audio Director
        timeline_data = None
        timeline_path = self.public_dir / "timeline.json"
        if timeline_path.exists():
            with open(timeline_path, "r", encoding="utf-8") as f:
                timeline_data = json.load(f)

        # Load subtitles data generated by Agent 3
        subs_json_path = self.public_dir / "subs.json"
        subs_data = {}
        if subs_json_path.exists():
            with open(subs_json_path, "r", encoding="utf-8") as f:
                subs_data = json.load(f)

        dialogue_turns = script_data.get("dialogue", [])
        fps = 30.0

        # Resolve 3D scenePreset and cast (4 Rotating Sets: diner, desk, living_room, rooftop)
        env_raw = str(script_data.get("environment", "diner")).lower()
        scene_preset = script_data.get("scenePreset") or script_data.get("scene_preset")
        if not scene_preset or scene_preset == "auto":
            if "living" in env_raw or "home" in env_raw or "dad" in str(script_data.get("dialogue", "")).lower():
                scene_preset = "living_room"
            elif "rooftop" in env_raw or "city" in env_raw or "night" in env_raw:
                scene_preset = "rooftop"
            elif "desk" in env_raw or "sunset" in env_raw:
                scene_preset = "desk"
            else:
                scene_preset = "diner"

        cast = script_data.get("cast") or {}
        speakers = [str(t.get("speaker", "")).lower() for t in dialogue_turns]
        char_ids = [str(t.get("character_id", "")).lower() for t in dialogue_turns]
        all_speaker_tokens = speakers + char_ids

        left_char = script_data.get("leftCharacterId") or cast.get("left")
        if not left_char:
            left_char = "dad" if any("dad" in s for s in all_speaker_tokens) else "junior_dev"

        right_char = script_data.get("rightCharacterId") or cast.get("right")
        if not right_char:
            right_char = "claude"
            for s in all_speaker_tokens:
                if "gemini" in s:
                    right_char = "gemini"
                    break
                elif "grok" in s:
                    right_char = "grok"
                    break
                elif "antigravity" in s:
                    right_char = "antigravity_bot"
                    break

        cast = {"left": left_char, "right": right_char}

        # Construct camera zoom cues
        camera_cues = []
        for t in dialogue_turns:
            start_frame = int(t.get("start", 0) * fps)
            end_frame = int(t.get("end", 0) * fps)
            speaker = t.get("speaker", "").lower()
            is_ai = "bot" in speaker or "gemini" in speaker or "claude" in speaker or "grok" in speaker or "codex" in speaker
            zoom = t.get("zoomLevel", 1.35 if is_ai else 1.15)
            target_x = 810 if is_ai else 270

            camera_cues.append({
                "startFrame": start_frame,
                "endFrame": end_frame,
                "zoomLevel": zoom,
                "targetX": target_x,
                "shake": t.get("emotion") == "angry" or (is_ai and t.get("emotion") == "smug")
            })

        # Remotion input props
        hook = script_data.get("hook", {})
        envelope = audio_result.get("envelope", [])

        # 1. Exact Act 3 (Turns 5-7) Multi-Step Card Timing calculation
        total_frames = (
            timeline_data.get("duration_in_frames")
            if timeline_data
            else int(audio_result.get("duration", 45) * fps)
        )
        turns_list = timeline_data.get("turns", []) if timeline_data else []
        turn_5_start = None
        turn_7_end = None

        if len(turns_list) > 5:
            turn_5_start = turns_list[5].get("start_frame")
            if len(turns_list) > 7:
                turn_7_end = turns_list[7].get("end_frame")
        elif len(turns_list) > 3:
            turn_5_start = turns_list[3].get("start_frame")
            turn_7_end = turn_5_start + 120

        if turn_5_start is None:
            turn_5_start = 450  # Default ~15.0s
        if turn_7_end is None:
            turn_7_end = turn_5_start + 360  # Default ~12.0s duration

        card_start_frame = turn_5_start
        card_end_frame = min(turn_7_end, total_frames - 90)
        card_duration_frames = max(30, card_end_frame - card_start_frame)

        # 2. Compile real topic-specific cardData from HookMasterAgent
        raw_card = script_data.get("cardData") or {}
        card_title = script_data.get("explainerTitle") or f"{script_data.get('title', 'Feature')[:24]} Specs"
        card_badge = script_data.get("badge") or "VERIFIED PROOF"

        rows = []
        if isinstance(raw_card, dict):
            if "rows" in raw_card and isinstance(raw_card["rows"], list):
                rows = raw_card["rows"]
            elif "items" in raw_card and isinstance(raw_card["items"], list):
                rows = raw_card["items"]
            else:
                for k, v in list(raw_card.items())[:3]:
                    clean_k = str(k).replace("_", " ").title()
                    val_str = str(v)
                    is_pos = not any(neg in val_str.lower() for neg in ["slow", "fail", "expensive", "fatigue", "manual", "high", "loss"])
                    status = "VERIFIED" if is_pos else "LIMITATION"
                    rows.append({
                        "label": clean_k,
                        "value": val_str,
                        "badge": status,
                        "status": status,
                        "isPositive": is_pos,
                    })
        elif isinstance(raw_card, list):
            rows = raw_card

        if not rows:
            topic_title = script_data.get("title", "Tech Feature")
            rows = [
                {"label": "Core Feature", "value": f"Verified: {topic_title[:24]}", "badge": "LIVE", "status": "LIVE", "isPositive": True},
                {"label": "System Access", "value": "Direct In-Browser Zero Cost", "badge": "FREE", "status": "FREE", "isPositive": True},
                {"label": "Setup Speed", "value": "Instant Execution Under 60s", "badge": "FAST", "status": "FAST", "isPositive": True},
            ]

        # Fetch verified media assets (SimpleIcons / IconHorse logo & GitHub OpenGraph / Thum.io proof card)
        topic_logo = script_data.get("topicLogoPath") or script_data.get("logoPath")
        proof_image = script_data.get("proofImagePath")
        try:
            from engine.agents.media_fetcher import fetch_topic_media_assets, attach_media_to_timeline
            media_assets = fetch_topic_media_assets(script_data, self.public_dir)
            if not topic_logo:
                topic_logo = media_assets.get("logoPath")
            if not proof_image:
                proof_image = media_assets.get("proofImagePath")
            if timeline_data:
                timeline_data["logoPath"] = topic_logo
                timeline_data["proofImagePath"] = proof_image
                attach_media_to_timeline(timeline_path, topic_logo, proof_image)
        except Exception as e:
            print(f"⚠️ SceneDirector: media fetcher notice: {e}")

        compiled_card_data = {
            "title": card_title,
            "subtitle": script_data.get("title", ""),
            "badge": card_badge,
            "type": script_data.get("cardType", "comparison"),
            "rows": rows,
            "items": rows,
            "startFrame": card_start_frame,
            "durationSeconds": card_duration_frames / fps,
            "durationFrames": card_duration_frames,
            "topicLogoPath": topic_logo,
            "logoPath": topic_logo,
            "proofImagePath": proof_image,
        }

        props_data = {
            "scenePreset": scene_preset,
            "cast": cast,
            "leftCharacterId": left_char,
            "rightCharacterId": right_char,
            "timeline": timeline_data,
            "subtitles": subs_data,
            "audioSrc": "voice.mp3",
            "topicLogoPath": topic_logo,
            "logoPath": topic_logo,
            "proofImagePath": proof_image,
            "ctaKeyword": script_data.get("cta_keyword") or script_data.get("ctaKeyword", "LINK"),
            "ctaText": script_data.get("cta_text") or script_data.get("ctaText") or f"💬 Comment {script_data.get('cta_keyword', 'LINK')} for the link",
            "environment": script_data.get("environment", "diner"),
            "weather": script_data.get("weather", "rain"),
            "weatherMode": script_data.get("weatherMode") or script_data.get("weather", "rain"),
            "episodeNumber": script_data.get("episode_number"),
            "episodeStr": script_data.get("episode_str"),
            "characters": script_data.get("characters", []),
            "screenContent": script_data.get("screenContent", "code"),
            "hookHeadline": hook.get("headline", "AI VS HUMANS"),
            "hookSubheadline": hook.get("subheadline", "Why AI is superior in every engineering area"),
            "hookTag": hook.get("tag", "⚠️ REAL TALK"),
            "explainerTitle": card_title,
            "comparisonRows": script_data.get("comparisonRows"),
            "leftHeader": script_data.get("leftHeader", "Anthropic Claude"),
            "rightHeader": script_data.get("rightHeader", "Google Antigravity"),
            "badge": card_badge,
            "cardType": script_data.get("cardType", "job_posting"),
            "cardUrl": script_data.get("cardUrl", "job-boards.greenhouse.io/anthropic/fellowship"),
            "cardData": compiled_card_data,
            "cardStartFrame": card_start_frame,
            "cardEndFrame": card_end_frame,
            "toastData": script_data.get("toastData"),
            "endCard": script_data.get("endCard"),
            "winner": script_data.get("winner", "Winner: Google Antigravity & Gemini 2.5 (100% Free Local Setup)"),
            "buttonText": script_data.get("buttonText", "Run `agy` Free"),
            "hasDad": any("dad" in str(c.get("type", "")).lower() or "dad" in str(c.get("name", "")).lower() for c in script_data.get("characters", [])) or any("dad" in t.get("speaker", "").lower() for t in subs_data.get("turns", [])),
            "bgImage": script_data.get("bgImage") or {
                "bangalore": "backgrounds/bg_bangalore.jpg",
                "bengaluru": "backgrounds/bg_bangalore.jpg",
                "indore": "backgrounds/bg_indore.jpg",
                "home": "backgrounds/bg_home.jpg",
                "inside_home": "backgrounds/bg_home.jpg",
                "desi_home": "backgrounds/bg_desi_home.jpg",
                "office": "backgrounds/bg_office.jpg",
                "modern_office": "backgrounds/bg_office.jpg",
                "outdoor": "backgrounds/bg_outdoor.jpg",
                "cafe": "backgrounds/bg_outdoor.jpg",
                "sunset": "backgrounds/bg_sunset.jpg",
                "noon": "backgrounds/bg_noon.jpg",
                "moonnight": "backgrounds/bg_moonnight.jpg",
                "night": "backgrounds/bg_moonnight.jpg",
                "cyber_diner": "backgrounds/bg_cyber_diner.jpg",
                "diner": "backgrounds/bg_cyber_diner.jpg",
                "server_room": "backgrounds/bg_server_room.jpg",
                "servers": "backgrounds/bg_server_room.jpg",
                "rooftop": "backgrounds/bg_rooftop.jpg",
                "cyber_lab": "backgrounds/bg_cyber_lab.jpg",
                "lab": "backgrounds/bg_cyber_lab.jpg",
            }.get(str(script_data.get("environment", "diner")).lower(), "backgrounds/bg_cyber_diner.jpg"),
            "cameraCues": camera_cues,
            "audioEnvelope": envelope,
            "enableSFX": True,
            "bgMusicVolume": 0.10,
        }

        # Write props to both public directories for rock-solid path resolution
        props_file = self.public_dir / "reel_props.json"
        with open(props_file, "w", encoding="utf-8") as f:
            json.dump(props_data, f, indent=2, ensure_ascii=False)
        dest_props = self.remotion_public / "reel_props.json"
        if os.path.realpath(str(props_file)) != os.path.realpath(str(dest_props)):
            shutil.copy2(props_file, dest_props)

        # Also mirror into public/video-meta.json for standard Remotion CI invocation
        meta_props_file = self.public_dir / "video-meta.json"
        with open(meta_props_file, "w", encoding="utf-8") as f:
            json.dump(props_data, f, indent=2, ensure_ascii=False)
        dest_meta = self.remotion_public / "video-meta.json"
        if os.path.realpath(str(meta_props_file)) != os.path.realpath(str(dest_meta)):
            shutil.copy2(meta_props_file, dest_meta)

        # Select composition
        composition_id = script_data.get("comp")
        if not composition_id:
            if script_data.get("style") == "threeway" or script_data.get("use_3d", False):
                composition_id = "ThreeWayComparisonReel"
            else:
                composition_id = "MasterAutonomousReel"

        # Output path
        final_output = self.out_dir / output_name

        # Detect system hardware capabilities
        cpu_count = os.cpu_count() or 4
        concurrency = min(4, max(1, cpu_count))
        has_gpu = bool(shutil.which("nvidia-smi"))

        print(f"⚡ [Agent 4] Hardware detected: {cpu_count} CPU cores (concurrency={concurrency}), GPU present={has_gpu}")
        print(f"⚡ [Agent 4] Executing Remotion Render: '{composition_id}' -> {final_output.name}...")
        start_time = time.time()

        base_cmd = [
            "npx", "remotion", "render",
            "src/index.ts",
            composition_id,
            str(final_output),
            "--props=public/video-meta.json",
        ]

        render_success = False
        last_error = ""

        if has_gpu:
            # Attempt 1: Fast GPU hardware rendering via angle-egl (Kaggle T4 / NVIDIA Linux)
            print("🚀 [Agent 4] Attempting GPU-accelerated render (--gl=angle-egl)...")
            cmd_gpu = base_cmd + [
                "--gl=angle-egl",
                f"--concurrency={concurrency}",
                "--codec=h264",
                "--pixel-format=yuv420p",
                "--x264-preset=medium",
                "--crf=18",
                "--jpeg-quality=95",
                "--timeout=180000"
            ]
            code, out = self._stream_remotion_render(cmd_gpu)
            if code == 0 and final_output.exists() and final_output.stat().st_size > 50_000:
                render_success = True
            else:
                last_error = out
                print(f"⚠️ [Agent 4] GPU angle-egl render failed (code {code}). Falling back to SwiftShader CPU engine...")

        if not render_success:
            # Fallback (or default non-GPU): Deterministic SwiftShader CPU rendering
            print(f"⚙️ [Agent 4] Executing CPU SwiftShader render (concurrency={concurrency})...")
            cmd_cpu = base_cmd + [
                "--gl=angle",
                "--angle=swiftshader",
                f"--concurrency={concurrency}",
                "--codec=h264",
                "--pixel-format=yuv420p",
                "--x264-preset=medium",
                "--crf=18",
                "--jpeg-quality=95",
                "--timeout=180000"
            ]
            code, out = self._stream_remotion_render(cmd_cpu)
            if code == 0 and final_output.exists() and final_output.stat().st_size > 50_000:
                render_success = True
            else:
                last_error = out

        if not render_success:
            print("❌ Remotion render failed:\n", last_error[-1000:])
            raise RuntimeError(f"Remotion render error: {last_error[-500:]}")

        render_sec = time.time() - start_time
        file_size_mb = final_output.stat().st_size / (1024 * 1024)
        print(f"✅ [Agent 4] Rendered successfully in {render_sec:.1f}s ({file_size_mb:.2f} MB)")

        # Auto-Export 4:5 Grid-Safe Cover Still (Frame 15: opening hook + logo)
        cover_still_path = final_output.with_name(f"{final_output.stem}_cover.png")
        try:
            print(f"📸 [Agent 4] Exporting 4:5 grid-safe cover still at Frame 15 -> {cover_still_path.name}...")
            still_cmd = [
                "npx", "remotion", "still",
                "src/index.ts",
                composition_id,
                str(cover_still_path),
                "--frame=15",
                "--props=public/video-meta.json"
            ]
            res = subprocess.run(
                still_cmd,
                cwd=str(self.remotion_dir),
                capture_output=True,
                text=True,
                timeout=90
            )
            if res.returncode == 0 and cover_still_path.exists():
                print(f"✅ [Agent 4] Cover still exported successfully ({cover_still_path.stat().st_size / 1024:.1f} KB)")
            else:
                print(f"⚠️ [Agent 4] Cover still export notice (exit {res.returncode}): {res.stderr[:200]}")
        except Exception as e_still:
            print(f"⚠️ [Agent 4] Cover still export notice (non-fatal): {e_still}")

        return str(final_output)

    def _stream_remotion_render(self, cmd: list) -> tuple[int, str]:
        """
        Executes Remotion render while streaming stdout & stderr live to console,
        ensuring real-time progress visibility in Kaggle notebooks and headless CI.
        """
        process = subprocess.Popen(
            cmd,
            cwd=str(self.remotion_dir),
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            bufsize=1,
            universal_newlines=True
        )
        output_buffer = []
        if process.stdout:
            for line in process.stdout:
                sys.stdout.write(line)
                sys.stdout.flush()
                output_buffer.append(line)
        returncode = process.wait()
        return returncode, "".join(output_buffer)


if __name__ == "__main__":
    print("Agent 4 Scene Director ready.")
